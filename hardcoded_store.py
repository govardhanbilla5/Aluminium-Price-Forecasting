class HardcodedMarketDataRepository(MarketDataRepository):
    """
    Serves market data from the in-memory dictionaries above.

    When replacing with live APIs, implement the same four methods in a new
    class (e.g. BlsLmeApiRepository) and inject it in main.py.
    """

    def get_lme(self, year_month: str) -> Optional[float]:
        value = _LME_DATA.get(year_month)
        if value is None:
            logger.warning("LME data missing for %s", year_month)
        return value

    def get_midwest_premium(self, year_month: str) -> Optional[float]:
        value = _MIDWEST_PREMIUM_DATA.get(year_month)
        if value is None:
            logger.warning("Midwest premium data missing for %s", year_month)
        return value

    def get_ppi(self, year_month: str) -> Optional[float]:
        value = _PPI_DATA.get(year_month)
        if value is None:
            logger.warning("PPI data missing for %s", year_month)
        return value

    def get_cng(self, year_month: str) -> Optional[float]:
        value = _CNG_DATA.get(year_month)
        if value is None:
            logger.warning("CNG data missing for %s", year_month)
        return value


class HardcodedPartRepository(PartRepository):
    """
    Serves part master data from the in-memory dictionaries above.

    Replace with an ERP adapter (SAP, Oracle, etc.) by implementing
    PartRepository and injecting the new class in main.py.
    """

    def get_part_weight(self, part_number: str) -> Optional[float]:
        weight = _PART_WEIGHT_MAP.get(part_number)
        if weight is None:
            logger.warning("Part weight not found for part number: %s", part_number)
        return weight

    def get_base_price(self, part_number: str, year_month: str) -> Optional[float]:
        part_prices = _BASE_PRICE_MAP.get(part_number)
        if part_prices is None:
            logger.warning("No price history found for part number: %s", part_number)
            return None
        return part_prices.get(year_month)

